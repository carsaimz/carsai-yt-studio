#!/usr/bin/env node
/**
 * generate-sw.mjs
 * Firebase Messaging's web push requires a plain (non-bundled) service worker
 * at the site root that calls firebase.initializeApp() with the SAME config
 * used by the main app. Since firebase-messaging-sw.js can't read
 * import.meta.env (it's loaded directly by the browser, not through Vite),
 * this script bakes the public Firebase config values into a static file
 * at build time. Firebase web config values are not secrets — they're safe
 * to ship in a public file (see Firebase's own docs).
 */
import { writeFileSync, mkdirSync } from "node:fs";

const cfg = {
  apiKey: process.env.VITE_FIREBASE_API_KEY ?? "",
  authDomain: process.env.VITE_FIREBASE_AUTH_DOMAIN ?? "",
  projectId: process.env.VITE_FIREBASE_PROJECT_ID ?? "",
  storageBucket: process.env.VITE_FIREBASE_STORAGE_BUCKET ?? "",
  messagingSenderId: process.env.VITE_FIREBASE_MESSAGING_SENDER_ID ?? "",
  appId: process.env.VITE_FIREBASE_APP_ID ?? "",
};

const sw = `// Auto-generated by scripts/generate-sw.mjs — do not edit by hand.
importScripts("https://www.gstatic.com/firebasejs/10.14.1/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/10.14.1/firebase-messaging-compat.js");

firebase.initializeApp(${JSON.stringify(cfg, null, 2)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const title = payload.notification?.title ?? "Carsai YT Studio";
  const options = {
    body: payload.notification?.body ?? "",
    icon: "/icon-192.png",
    badge: "/favicon-32.png",
    data: payload.data ?? {},
  };
  self.registration.showNotification(title, options);
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = event.notification.data?.url ?? "/";
  event.waitUntil(clients.openWindow(url));
});
`;

mkdirSync("public", { recursive: true });
writeFileSync("public/firebase-messaging-sw.js", sw);
console.log("public/firebase-messaging-sw.js generated");
